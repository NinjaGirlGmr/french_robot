static void ssd1306_command(uint8_t cmd) {
    uint8_t data[2] = {0x00, cmd};
    i2c_write_blocking(oled_i2c, oled_addr, data, 2, false);
}

static void ssd1306_command_list(const uint8_t *cmds, size_t count) {
    for (size_t i = 0; i < count; i++) {
        ssd1306_command(cmds[i]);
    }
}

void ssd1306_init(i2c_inst_t *i2c, uint sda_pin, uint scl_pin, uint8_t addr) {
    oled_i2c = i2c;
    oled_addr = addr;

    i2c_init(oled_i2c, OLED_I2C_BAUD);
    gpio_set_function(sda_pin, GPIO_FUNC_I2C);
    gpio_set_function(scl_pin, GPIO_FUNC_I2C);
    gpio_pull_up(sda_pin);
    gpio_pull_up(scl_pin);

    static const uint8_t init_cmds[] = {
        0xAE,       // display off
        0x20, 0x00, // memory addressing mode: horizontal
        0xB0,       // page start 0
        0xC8,       // COM scan dec
        0x00,       // low column
        0x10,       // high column
        0x40,       // start line
        0x81, 0x7F, // contrast
        0xA1,       // segment remap
        0xA6,       // normal display
        0xA8, 0x3F, // multiplex
        0xA4,       // display follows RAM
        0xD3, 0x00, // display offset
        0xD5, 0x80, // clock divide
        0xD9, 0xF1, // pre-charge
        0xDA, 0x12, // COM pins
        0xDB, 0x40, // VCOM detect
        0x8D, 0x14, // charge pump on
        0xAF        // display on
    };
    ssd1306_command_list(init_cmds, sizeof(init_cmds));

    ssd1306_clear();
    ssd1306_flush();
}

void ssd1306_clear(void) {
    memset(buffer, 0, sizeof(buffer));
}

static void draw_char(uint8_t x, uint8_t y, char c) {
    if (c < 32 || c > 127) {
        c = '?';
    }
    uint8_t idx = (uint8_t)c - 32;
    if (x >= SSD1306_WIDTH || y >= 8) {
        return;
    }
    size_t base = (size_t)y * SSD1306_WIDTH + x;
    for (int col = 0; col < 5; col++) {
        size_t pos = base + (size_t)col;
        if (pos < sizeof(buffer)) {
            buffer[pos] = font5x7[idx][col];
        }
    }
    // spacing column
    if (base + 5 < sizeof(buffer)) {
        buffer[base + 5] = 0x00;
    }
}

void ssd1306_draw_text(uint8_t x, uint8_t y, const char *text) {
    // y is page (0..7), x is pixel column.
    while (*text && x + 6 <= SSD1306_WIDTH) {
        draw_char(x, y, *text++);
        x += 6;
    }
}

void ssd1306_flush(void) {
    uint8_t setup[] = {0x00, 0x21, 0x00, SSD1306_WIDTH - 1, 0x22, 0x00, 7};
    i2c_write_blocking(oled_i2c, oled_addr, setup, sizeof(setup), false);

    uint8_t prefix = 0x40;
    // Send buffer in chunks to avoid large stack allocations.
    for (size_t i = 0; i < sizeof(buffer);) {
        uint8_t chunk[17];
        chunk[0] = prefix;
        size_t to_copy = (sizeof(chunk) - 1);
        if (to_copy > sizeof(buffer) - i) {
            to_copy = sizeof(buffer) - i;
        }
        memcpy(&chunk[1], &buffer[i], to_copy);
        i2c_write_blocking(oled_i2c, oled_addr, chunk, to_copy + 1, false);
        i += to_copy;
    }
}
